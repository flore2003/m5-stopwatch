#!/usr/bin/env python3
"""Convert a TrueType font into glyph outlines for lib/StopWatchDisplay (swd::FontData).

Usage (fontTools comes in via uv):
  uv run --with fonttools python tools/font2cpp.py tools/fonts/Inter.ttf InterRegular \
      --axis wght=400 --axis opsz=14 > lib/StopWatchDisplay/src/fonts/InterRegular.cpp

Outlines keep the font's own units (y up) and curves (quadratic for TrueType),
so text can be drawn at any size and angle by the engine's path filler. The
character set is printable ASCII plus a few symbols (see CHARSET).

Tabular alternates (OpenType 'tnum', equal-width digits) are emitted under
private-use codepoints U+E000 + the original character, for
TextItem::setTabularNumbers().
"""

import argparse
import sys

from fontTools.pens.basePen import decomposeQuadraticSegment
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

CHARSET = [chr(c) for c in range(32, 127)] + list("°·–—…×←↑→↓•")

OP_MOVE, OP_LINE, OP_QUAD, OP_CUBIC, OP_CLOSE = 0, 1, 2, 3, 4
TABULAR_BASE = 0xE000


def feature_substitutions(font, tag):
    """Single substitutions (glyph name -> glyph name) of a GSUB feature."""
    subs = {}
    if "GSUB" not in font:
        return subs
    gsub = font["GSUB"].table
    for record in gsub.FeatureList.FeatureRecord:
        if record.FeatureTag != tag:
            continue
        for index in record.Feature.LookupListIndex:
            lookup = gsub.LookupList.Lookup[index]
            for sub in lookup.SubTable:
                sub = getattr(sub, "ExtSubTable", sub)
                subs.update(getattr(sub, "mapping", None) or {})
    return subs


def glyph_ops(glyphset, name):
    """Return the glyph outline as a flat list of int16: op codes and coordinates."""
    pen = DecomposingRecordingPen(glyphset)
    glyphset[name].draw(pen)
    out = []
    for op, args in pen.value:
        if op == "moveTo":
            out += [OP_MOVE, *map(round, args[0])]
        elif op == "lineTo":
            out += [OP_LINE, *map(round, args[0])]
        elif op == "qCurveTo":
            if args[-1] is None:
                # A contour made only of off-curve points: close it on itself.
                raise ValueError(f"glyph {name}: implied-point-only contour not supported")
            for (cx, cy), (x, y) in decomposeQuadraticSegment(args):
                out += [OP_QUAD, round(cx), round(cy), round(x), round(y)]
        elif op == "curveTo":
            (c1, c2, p) = args
            out += [OP_CUBIC, *map(round, c1), *map(round, c2), *map(round, p)]
        elif op in ("closePath", "endPath"):
            out += [OP_CLOSE]
        else:
            raise ValueError(f"glyph {name}: unsupported pen op {op}")
    for v in out:
        if not -32768 <= v <= 32767:
            raise ValueError(f"glyph {name}: coordinate {v} out of int16 range")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("font")
    ap.add_argument("symbol", help="C++ name, e.g. InterRegular (emits swd::fonts::InterRegular)")
    ap.add_argument("--axis", action="append", default=[], help="variable font axis, e.g. wght=400")
    args = ap.parse_args()

    font = TTFont(args.font)
    if "fvar" in font:
        axes = {a.axisTag: a.defaultValue for a in font["fvar"].axes}
        for spec in args.axis:
            tag, value = spec.split("=")
            axes[tag] = float(value)
        font = instantiateVariableFont(font, axes)

    upm = font["head"].unitsPerEm
    os2 = font["OS/2"]
    cmap = font.getBestCmap()
    glyphset = font.getGlyphSet()
    hmtx = font["hmtx"]

    entries = []  # (codepoint, glyph name)
    missing = []
    for ch in sorted(set(CHARSET), key=ord):
        name = cmap.get(ord(ch))
        if name is None:
            missing.append(ch)
        else:
            entries.append((ord(ch), name))
    tnum = feature_substitutions(font, "tnum")
    entries += [(TABULAR_BASE + cp, tnum[name]) for cp, name in entries if cp < 0x100 and name in tnum]

    glyphs, data = [], []
    for cp, name in sorted(entries):
        ops = glyph_ops(glyphset, name)
        glyphs.append((cp, hmtx[name][0], len(data), len(ops)))
        data += ops
    if missing:
        print(f"warning: not in font: {''.join(missing)!r}", file=sys.stderr)

    w = sys.stdout.write
    w(f"// Generated by tools/font2cpp.py from {args.font.split('/')[-1]} ({' '.join(args.axis)}). Do not edit.\n")
    w("// Font license: see tools/fonts (SIL Open Font License 1.1).\n")
    w('#include "../Text.h"\n\nnamespace swd {\nnamespace fonts {\nnamespace {\n\n')
    w("const GlyphData kGlyphs[] = {\n")
    for cp, adv, off, n in glyphs:
        w(f"    {{{cp}, {adv}, {off}, {n}}},\n")
    w("};\n\nconst int16_t kData[] = {\n")
    for i in range(0, len(data), 24):
        w("    " + ", ".join(map(str, data[i:i + 24])) + ",\n")
    w("};\n\n}  // namespace\n\n")
    w(f"extern const FontData {args.symbol} = {{\n")
    w(f'    "{args.symbol}", {upm}, {os2.sTypoAscender}, {os2.sTypoDescender}, '
      f"{getattr(os2, 'sCapHeight', 0)}, {getattr(os2, 'sxHeight', 0)},\n")
    w(f"    {len(glyphs)}, kGlyphs, kData}};\n\n}}  // namespace fonts\n}}  // namespace swd\n")
    print(f"{args.symbol}: {len(glyphs)} glyphs, {len(data)} values ({len(data) * 2 + len(glyphs) * 10} bytes)",
          file=sys.stderr)


if __name__ == "__main__":
    main()
